CREATE TABLE IF NOT EXISTS public.prop_bet_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prop_bet_id bigint NOT NULL REFERENCES public.prop_bets(id) ON DELETE CASCADE,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  vote_text text NOT NULL,
  outcome_text text NOT NULL,
  is_correct boolean NOT NULL,
  wager_label text NOT NULL,
  settled_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  UNIQUE (prop_bet_id, user_id)
);

CREATE INDEX IF NOT EXISTS prop_bet_results_event_id_user_id_idx
  ON public.prop_bet_results (event_id, user_id, settled_at DESC);

CREATE INDEX IF NOT EXISTS prop_bet_results_user_id_correct_idx
  ON public.prop_bet_results (user_id, is_correct, settled_at DESC);

CREATE OR REPLACE FUNCTION public.settle_prop_pix_results()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.status = 'closed' AND OLD.status IS DISTINCT FROM 'closed' THEN
    INSERT INTO public.prop_bet_results (
      prop_bet_id,
      event_id,
      user_id,
      vote_text,
      outcome_text,
      is_correct,
      wager_label
    )
    SELECT
      NEW.id,
      NEW.event_id,
      v.user_id,
      btrim(COALESCE(o.label, v.response_text, '')),
      btrim(NEW.outcome_text),
      lower(btrim(COALESCE(o.label, v.response_text, ''))) = lower(btrim(NEW.outcome_text)),
      NEW.wager_label
    FROM public.prop_bet_votes v
    LEFT JOIN public.prop_bet_options o ON o.id = v.option_id
    WHERE v.prop_bet_id = NEW.id
    ON CONFLICT (prop_bet_id, user_id) DO NOTHING;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS settle_prop_bet_results_on_close ON public.prop_bets;
CREATE TRIGGER settle_prop_bet_results_on_close
AFTER UPDATE OF status, outcome_text ON public.prop_bets
FOR EACH ROW
EXECUTE FUNCTION public.settle_prop_pix_results();
