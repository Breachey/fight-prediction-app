CREATE TABLE IF NOT EXISTS public.prop_bets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  creator_user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  question text NOT NULL CHECK (char_length(btrim(question)) BETWEEN 3 AND 240),
  response_type text NOT NULL CHECK (response_type IN ('options', 'manual')),
  wager_label text NOT NULL CHECK (char_length(btrim(wager_label)) BETWEEN 1 AND 80),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'claim_pending', 'closed', 'cancelled')),
  outcome_text text,
  closed_at timestamptz,
  closed_by_claim_id bigint,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.prop_bet_options (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prop_bet_id bigint NOT NULL REFERENCES public.prop_bets(id) ON DELETE CASCADE,
  label text NOT NULL CHECK (char_length(btrim(label)) BETWEEN 1 AND 120),
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  UNIQUE (prop_bet_id, label),
  UNIQUE (prop_bet_id, sort_order)
);

CREATE TABLE IF NOT EXISTS public.prop_bet_votes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prop_bet_id bigint NOT NULL REFERENCES public.prop_bets(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  option_id bigint REFERENCES public.prop_bet_options(id) ON DELETE SET NULL,
  response_text text CHECK (response_text IS NULL OR char_length(btrim(response_text)) BETWEEN 1 AND 240),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  UNIQUE (prop_bet_id, user_id),
  CHECK ((option_id IS NULL) <> (response_text IS NULL))
);

CREATE TABLE IF NOT EXISTS public.prop_bet_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prop_bet_id bigint NOT NULL REFERENCES public.prop_bets(id) ON DELETE CASCADE,
  claimant_user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  outcome_text text NOT NULL CHECK (char_length(btrim(outcome_text)) BETWEEN 1 AND 240),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'rejected')),
  confirming_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  confirmed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  actor_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
  notification_type text NOT NULL CHECK (char_length(btrim(notification_type)) BETWEEN 1 AND 80),
  entity_type text,
  entity_id bigint,
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 160),
  body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 500),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

ALTER TABLE public.prop_bets
