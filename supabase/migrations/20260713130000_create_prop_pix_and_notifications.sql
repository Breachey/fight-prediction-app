CREATE OR REPLACE FUNCTION public.set_prop_pix_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at = timezone('utc', now());
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_prop_bets_updated_at ON public.prop_bets;
CREATE TRIGGER set_prop_bets_updated_at
BEFORE UPDATE ON public.prop_bets
FOR EACH ROW
EXECUTE FUNCTION public.set_prop_pix_updated_at();

