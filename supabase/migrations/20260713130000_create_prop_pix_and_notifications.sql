CREATE TRIGGER set_prop_bet_votes_updated_at
BEFORE UPDATE ON public.prop_bet_votes
FOR EACH ROW
EXECUTE FUNCTION public.set_prop_pix_updated_at();

CREATE OR REPLACE FUNCTION public.confirm_prop_pix_claim(
  p_claim_id bigint,
  p_confirming_user_id bigint
)
RETURNS TABLE (
  prop_bet_id bigint,
  claim_id bigint,
  claimant_user_id bigint,
  confirming_user_id bigint,
  outcome_text text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  claim_row public.prop_bet_claims%ROWTYPE;
BEGIN
  SELECT c.*
  INTO claim_row
  FROM public.prop_bet_claims c
  JOIN public.prop_bets b ON b.id = c.prop_bet_id
  WHERE c.id = p_claim_id
    AND c.status = 'pending'
    AND b.status = 'claim_pending'
  FOR UPDATE OF c;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Claim is no longer pending';
  END IF;

  PERFORM 1
  FROM public.prop_bets b
  WHERE b.id = claim_row.prop_bet_id
  FOR UPDATE;

  IF p_confirming_user_id = claim_row.claimant_user_id THEN
    RAISE EXCEPTION 'Claimant cannot confirm their own claim';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.prop_bet_votes v
    WHERE v.prop_bet_id = claim_row.prop_bet_id
      AND v.user_id = p_confirming_user_id
  ) THEN
    RAISE EXCEPTION 'Only voters can confirm a claim';
  END IF;

  UPDATE public.prop_bet_claims
  SET status = 'confirmed',
      confirming_user_id = p_confirming_user_id,
      confirmed_at = timezone('utc', now())
  WHERE id = claim_row.id;

  UPDATE public.prop_bets
  SET status = 'closed',
      outcome_text = claim_row.outcome_text,
      closed_at = timezone('utc', now()),
      closed_by_claim_id = claim_row.id
  WHERE id = claim_row.prop_bet_id;

  RETURN QUERY
  SELECT claim_row.prop_bet_id,
         claim_row.id,
         claim_row.claimant_user_id,
         p_confirming_user_id,
         claim_row.outcome_text;
END;
$$;

